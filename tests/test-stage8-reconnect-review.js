const assert = require('assert')
const Y = require('yjs')
const local = new Y.Doc(); local.getText('body').insert(0, 'before disconnect')
const before = Y.snapshot(local)
const remote = new Y.Doc(); Y.applyUpdate(remote, Y.encodeStateAsUpdate(local)); remote.getText('body').insert(remote.getText('body').length, ' — teammate edit')
Y.applyUpdate(local, Y.encodeStateAsUpdate(remote))
assert(!Y.equalSnapshots(before, Y.snapshot(local)), 'reconnect must detect a state change from its pre-disconnect snapshot')
assert(local.getText('body').toString().includes('teammate edit'))
console.log('PASS: reconnect snapshot detects remote-since-disconnect changes for decoration review')
